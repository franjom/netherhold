using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;

namespace DK2.Tools.Wiki;

/// <summary>One open-questions.md row: its number, question, state word and the notes it cites.</summary>
public sealed record QuestionRow(string Id, string Question, string State, IReadOnlyList<string> CitedNotes)
{
    /// <summary>States that close a question; any other leading phrase (OPEN, PARTLY ANSWERED, OWNER QUESTION,
    /// UNKNOWN and so on) leaves it open.</summary>
    static readonly string[] ClosedStates =
        ["ANSWERED", "ANSWERED AND BUILT", "BUILT", "CLOSED", "CONFIRMED", "MEASURED", "READ", "STRONGLY INFERRED",
         "SUPERSEDED", "WITHDRAWN", "YES"];

    public bool IsOpen => !ClosedStates.Contains(State);
}

/// <summary>Everything the generated pages read, loaded once.</summary>
public sealed record WikiInputs(
    SystemCatalog Catalog,
    IReadOnlyList<ResearchNote> Notes,
    IReadOnlyList<Adr> Adrs,
    IReadOnlyList<QuestionRow> Questions,
    IReadOnlyList<FunctionRecord> Records,
    IReadOnlySet<int> AdrsCitedInCode);

/// <summary>
/// The wiki's generated pages (ADR-0643). Output is byte-stable: LF endings, ordinal sorts, invariant
/// numbers, and no dates or commit ids, so an unchanged master makes no wiki commit.
/// </summary>
public static partial class WikiPages
{
    public const string Blob = "https://github.com/franjom/netherhold/blob/master/";
    const string Unassigned = "Unassigned";

    [GeneratedRegex(@"^\| (Q\d+[a-z]?) \|")] private static partial Regex QuestionRx();
    [GeneratedRegex(@"(?<![\w/.-])(?:docs/research/|research/)?([a-z0-9][a-z0-9-]*)\.md\b")] private static partial Regex NoteRx();
    [GeneratedRegex(@"^[\s*_`]*([A-Z]+(?: [A-Z]+)*)\b")] private static partial Regex StateRx();

    /// <summary>Page file name to content, in the order the pages are listed.</summary>
    public static IReadOnlyList<(string File, string Content)> All(WikiInputs inputs) =>
    [
        ("Decisions-by-System.md", DecisionsBySystem(inputs)),
        ("Research-by-System.md", ResearchBySystem(inputs)),
        ("Open-Questions.md", OpenQuestions(inputs)),
        ("Status-Matrix.md", StatusMatrix(inputs)),
        ("KB-Coverage.md", KbCoverage(inputs)),
    ];

    /// <summary>The rows of open-questions.md that start <c>| Qn |</c>.</summary>
    public static IReadOnlyList<QuestionRow> ParseQuestions(IEnumerable<string> lines, ISet<string> noteNames)
    {
        var rows = new List<QuestionRow>();
        foreach (string line in lines)
        {
            var m = QuestionRx().Match(line);
            if (!m.Success) continue;
            string[] cells = line.Split('|');
            string question = cells.Length > 2 ? cells[2].Trim() : "";
            var state = StateRx().Match(cells.Length > 3 ? cells[3] : "");
            var cited = NoteRx().Matches(line).Select(n => n.Groups[1].Value).Where(noteNames.Contains)
                .Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal).ToArray();
            rows.Add(new QuestionRow(m.Groups[1].Value, question,
                state.Success ? state.Groups[1].Value : "", cited));
        }
        return rows;
    }

    static Dictionary<string, IReadOnlyList<string>> NoteSystems(WikiInputs inputs)
        => inputs.Notes.ToDictionary(n => n.Name, n => n.Systems, StringComparer.Ordinal);

    /// <summary>System id to the items in it; an item with no system goes under <see cref="Unassigned"/>.</summary>
    static Dictionary<string, List<T>> Group<T>(IEnumerable<T> items, Func<T, IEnumerable<string>> systems)
    {
        var groups = new Dictionary<string, List<T>>(StringComparer.Ordinal);
        foreach (T item in items)
        {
            bool any = false;
            foreach (string s in systems(item))
            {
                any = true;
                (groups.TryGetValue(s, out var list) ? list : groups[s] = []).Add(item);
            }
            if (!any) (groups.TryGetValue(Unassigned, out var list) ? list : groups[Unassigned] = []).Add(item);
        }
        return groups;
    }

    static StringBuilder Header(string title, string source)
        => new StringBuilder()
            .Append("# ").Append(title).Append("\n\n")
            .Append("Generated by `dk2tools wiki` from ").Append(source)
            .Append(". Edit the sources, not this page; systems are listed in [`docs/systems.yaml`](")
            .Append(Blob).Append("docs/systems.yaml) (ADR-0643).\n\n");

    static void Contents(StringBuilder sb, WikiInputs inputs, Func<string, int> count, bool unassigned)
    {
        foreach (SystemEntry s in inputs.Catalog.Systems)
            sb.Append("- [").Append(s.Title).Append("](#").Append(FunctionKb.Slug(s.Title)).Append(") (").Append(N(count(s.Id))).Append(")\n");
        if (unassigned) sb.Append("- [").Append(Unassigned).Append("](#unassigned) (").Append(N(count(Unassigned))).Append(")\n");
        sb.Append('\n');
    }

    static void SystemHeading(StringBuilder sb, SystemEntry s)
        => sb.Append("## ").Append(s.Title).Append("\n\n").Append(s.Scope).Append(" System id `").Append(s.Id).Append("`.\n\n");

    static string N(int n) => n.ToString(CultureInfo.InvariantCulture);

    static string Cell(string text) => text.Replace("|", "\\|").Replace("\n", " ").Trim();

    static string AdrLink(Adr adr)
        => $"[{adr.Number:D4}]({Blob}{AdrIndex.RelativePath}#{FunctionKb.Slug(adr.Heading)})";

    static string NoteLink(string name) => $"[`{name}.md`]({Blob}{ResearchNotes.Folder}/{name}.md)";

    public static string DecisionsBySystem(WikiInputs inputs)
    {
        var noteSystems = NoteSystems(inputs);
        var byNumber = inputs.Adrs.GroupBy(a => a.Number).ToDictionary(g => g.Key, g => g.First());
        var groups = Group(inputs.Adrs, a => AdrIndex.Systems(a, noteSystems, inputs.Catalog));
        var sb = Header("Decisions by System", $"[`{AdrIndex.RelativePath}`]({Blob}{AdrIndex.RelativePath})");
        sb.Append(N(inputs.Adrs.Count)).Append(" ADRs. One that spans several systems is listed under each.\n\n");
        Contents(sb, inputs, id => groups.TryGetValue(id, out var l) ? l.Count : 0, groups.ContainsKey(Unassigned));

        void Table(List<Adr> adrs)
        {
            sb.Append("| ADR | Decision | Status |\n|---|---|---|\n");
            foreach (Adr a in adrs.OrderBy(a => a.Number).ThenBy(a => a.Line))
            {
                string status = a.Status.Length > 0 ? a.Status : "?";
                if (a.SupersededBy is int by)
                    status += byNumber.TryGetValue(by, out var next) ? $" by {AdrLink(next)}" : $" by {by:D4}";
                sb.Append("| ").Append(AdrLink(a)).Append(" | ").Append(Cell(a.Title)).Append(" | ").Append(status).Append(" |\n");
            }
            sb.Append('\n');
        }

        foreach (SystemEntry s in inputs.Catalog.Systems)
        {
            SystemHeading(sb, s);
            if (groups.TryGetValue(s.Id, out var adrs)) Table(adrs);
            else sb.Append("No ADR yet.\n\n");
        }
        if (groups.TryGetValue(Unassigned, out var rest))
        {
            sb.Append("## ").Append(Unassigned).Append("\n\nNo system: they cite no tagged note and carry no **Systems:** field.\n\n");
            Table(rest);
        }

        var gaps = AdrIndex.Gaps(inputs.Adrs).ToArray();
        sb.Append("## Numbers not used\n\n");
        sb.Append(gaps.Length == 0 ? "None." : string.Join(", ", gaps.Select(g => g.ToString("D4", CultureInfo.InvariantCulture))) + ".");
        sb.Append(" These numbers were never given to an ADR.\n");
        return sb.ToString();
    }

    public static string ResearchBySystem(WikiInputs inputs)
    {
        var groups = Group(inputs.Notes, n => n.Systems);
        var sb = Header("Research by System", $"the front matter of [`{ResearchNotes.Folder}/`]({Blob.Replace("/blob/", "/tree/")}{ResearchNotes.Folder})");
        sb.Append(N(inputs.Notes.Count)).Append(" research notes. A note that spans several systems is listed under each.\n\n");
        Contents(sb, inputs, id => groups.TryGetValue(id, out var l) ? l.Count : 0, groups.ContainsKey(Unassigned));

        void Table(List<ResearchNote> notes)
        {
            sb.Append("| Note | File |\n|---|---|\n");
            foreach (ResearchNote n in notes.OrderBy(n => n.Title, StringComparer.Ordinal).ThenBy(n => n.Name, StringComparer.Ordinal))
                sb.Append("| ").Append(Cell(n.Title)).Append(" | ").Append(NoteLink(n.Name)).Append(" |\n");
            sb.Append('\n');
        }

        foreach (SystemEntry s in inputs.Catalog.Systems)
        {
            SystemHeading(sb, s);
            if (groups.TryGetValue(s.Id, out var notes)) Table(notes);
            else sb.Append("No research note yet.\n\n");
        }
        if (groups.TryGetValue(Unassigned, out var rest))
        {
            sb.Append("## ").Append(Unassigned).Append("\n\n");
            Table(rest);
        }
        return sb.ToString().TrimEnd('\n') + "\n";
    }

    public static string OpenQuestions(WikiInputs inputs)
    {
        var noteSystems = NoteSystems(inputs);
        var open = inputs.Questions.Where(q => q.IsOpen).ToArray();
        var groups = Group(open, q => q.CitedNotes.SelectMany(n => noteSystems.TryGetValue(n, out var s) ? s : [])
            .Distinct(StringComparer.Ordinal));
        string file = $"{ResearchNotes.Folder}/{ResearchNotes.OpenQuestions}.md";
        var sb = Header("Open Questions", $"[`{file}`]({Blob}{file})");
        sb.Append(N(open.Length)).Append(" of ").Append(N(inputs.Questions.Count))
          .Append(" questions are open: their state is not one that closes a question (ANSWERED, BUILT, CLOSED, STRONGLY INFERRED and the like). ")
          .Append("A question takes the systems of the notes its row cites; one citing none is unassigned.\n\n");
        Contents(sb, inputs, id => groups.TryGetValue(id, out var l) ? l.Count : 0, groups.ContainsKey(Unassigned));

        void Table(List<QuestionRow> rows)
        {
            sb.Append("| Q | Question | State |\n|---|---|---|\n");
            foreach (QuestionRow q in rows.OrderBy(q => QuestionNumber(q.Id)).ThenBy(q => q.Id, StringComparer.Ordinal))
                sb.Append("| ").Append(q.Id).Append(" | ").Append(Cell(q.Question)).Append(" | ").Append(q.State).Append(" |\n");
            sb.Append('\n');
        }

        foreach (SystemEntry s in inputs.Catalog.Systems)
        {
            SystemHeading(sb, s);
            if (groups.TryGetValue(s.Id, out var rows)) Table(rows);
            else sb.Append("No open question.\n\n");
        }
        if (groups.TryGetValue(Unassigned, out var rest))
        {
            sb.Append("## ").Append(Unassigned).Append("\n\n");
            Table(rest);
        }
        return sb.ToString().TrimEnd('\n') + "\n";
    }

    static int QuestionNumber(string id) => int.Parse(new string(id.Skip(1).TakeWhile(char.IsAsciiDigit).ToArray()), CultureInfo.InvariantCulture);

    /// <summary>A record's systems: those of the notes its evidence links point into.</summary>
    static IEnumerable<string> RecordSystems(FunctionRecord r, IReadOnlyDictionary<string, IReadOnlyList<string>> noteSystems)
        => r.Evidence
            .Select(e => ResearchNotes.NoteName(e.Split('#')[0]))
            .Where(n => n is not null)
            .SelectMany(n => noteSystems.TryGetValue(n!, out var s) ? s : [])
            .Distinct(StringComparer.Ordinal);

    public static string StatusMatrix(WikiInputs inputs)
    {
        var noteSystems = NoteSystems(inputs);
        var notes = Group(inputs.Notes, n => n.Systems);
        var adrs = Group(inputs.Adrs, a => AdrIndex.Systems(a, noteSystems, inputs.Catalog));
        var questions = Group(inputs.Questions.Where(q => q.IsOpen),
            q => q.CitedNotes.SelectMany(n => noteSystems.TryGetValue(n, out var s) ? s : []).Distinct(StringComparer.Ordinal));
        var records = Group(inputs.Records.Where(r => r.Status != "SUPERSEDED"), r => RecordSystems(r, noteSystems));

        int Count<T>(Dictionary<string, List<T>> g, string id, Func<T, bool>? where = null)
            => g.TryGetValue(id, out var l) ? (where is null ? l.Count : l.Count(where)) : 0;

        var sb = Header("Status Matrix", "the research notes, `docs/DECISIONS.md`, `open-questions.md` and the function records");
        sb.Append("Per system: research notes; ADRs in force (accepted or amended), how many of them our code cites, ")
          .Append("superseded or withdrawn, and proposed; open questions; and DKII.EXE function records whose evidence links into ")
          .Append("the system's notes, with how many our code mirrors whole (BUILT) and in part (PARTIAL).\n\n");
        sb.Append("An ADR's status says it was decided, not that it was built: `accepted` stays when the code lands (ADR-0660). ")
          .Append("\"Cited in code\" counts ADRs whose number appears in `src/` or the Unity scripts. It is a floor, not a census: ")
          .Append("built decisions are not always cited, process and research decisions have no code to cite them, and a ")
          .Append("citation can mark a partial build.\n\n");
        sb.Append("| System | Notes | ADRs in force | Cited in code | Superseded | Proposed | Open questions | Function records | Built | Partial |\n");
        sb.Append("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n");
        foreach (SystemEntry s in inputs.Catalog.Systems)
        {
            sb.Append("| [").Append(s.Title).Append("](Decisions-by-System#").Append(FunctionKb.Slug(s.Title)).Append(") | ")
              .Append(N(Count(notes, s.Id))).Append(" | ")
              .Append(N(Count(adrs, s.Id, a => a.Status is "accepted" or "amended"))).Append(" | ")
              .Append(N(Count(adrs, s.Id, a => a.Status is "accepted" or "amended" && inputs.AdrsCitedInCode.Contains(a.Number)))).Append(" | ")
              .Append(N(Count(adrs, s.Id, a => a.Status is "superseded" or "withdrawn"))).Append(" | ")
              .Append(N(Count(adrs, s.Id, a => a.Status is "proposed"))).Append(" | ")
              .Append(N(Count(questions, s.Id))).Append(" | ")
              .Append(N(Count(records, s.Id))).Append(" | ")
              .Append(N(Count(records, s.Id, r => r.Status == "BUILT"))).Append(" | ")
              .Append(N(Count(records, s.Id, r => r.Status == "PARTIAL"))).Append(" |\n");
        }
        return sb.ToString();
    }

    public static string KbCoverage(WikiInputs inputs)
    {
        var noteSystems = NoteSystems(inputs);
        string[] confidences = FunctionKb.Confidences;
        string[] statuses = FunctionKb.Statuses;
        var sb = Header("KB Coverage", $"the function records in [`{FunctionKb.Folder}/`]({Blob.Replace("/blob/", "/tree/")}{FunctionKb.Folder})");
        sb.Append(N(inputs.Records.Count)).Append(" records. Confidence is the one scale of ADR-0642: CONFIRMED needs the running game, ")
          .Append("a binary read alone is STRONGLY INFERRED. READ means read in DKII.EXE, PARTIAL that our code mirrors part of it, BUILT all of it (ADR-0660).\n\n");

        sb.Append("## By confidence and status\n\n| Confidence | ").Append(string.Join(" | ", statuses)).Append(" | Total |\n|---|");
        sb.Append(string.Concat(Enumerable.Repeat("---:|", statuses.Length + 1))).Append('\n');
        foreach (string c in confidences)
        {
            sb.Append("| ").Append(c);
            foreach (string st in statuses)
                sb.Append(" | ").Append(N(inputs.Records.Count(r => r.Confidence == c && r.Status == st)));
            sb.Append(" | ").Append(N(inputs.Records.Count(r => r.Confidence == c))).Append(" |\n");
        }
        sb.Append("| Total");
        foreach (string st in statuses) sb.Append(" | ").Append(N(inputs.Records.Count(r => r.Status == st)));
        sb.Append(" | ").Append(N(inputs.Records.Count)).Append(" |\n\n");

        var groups = Group(inputs.Records, r => RecordSystems(r, noteSystems));
        sb.Append("## By system\n\nA record counts under each system its evidence links into.\n\n| System | ")
          .Append(string.Join(" | ", confidences)).Append(" | Total |\n|---|")
          .Append(string.Concat(Enumerable.Repeat("---:|", confidences.Length + 1))).Append('\n');
        var rows = inputs.Catalog.Systems.Select(s => (s.Id, s.Title)).ToList();
        if (groups.ContainsKey(Unassigned)) rows.Add((Unassigned, Unassigned));
        foreach (var (id, title) in rows)
        {
            var list = groups.TryGetValue(id, out var l) ? l : [];
            sb.Append("| ").Append(title);
            foreach (string c in confidences) sb.Append(" | ").Append(N(list.Count(r => r.Confidence == c)));
            sb.Append(" | ").Append(N(list.Count)).Append(" |\n");
        }
        return sb.ToString();
    }
}
