using System.Globalization;
using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using DK2.Tools.Wiki;

namespace DK2.Tools.SimMatrix;

/// <summary>The matrix as a wiki page and as JSON. Both are byte-stable for one source tree.</summary>
internal static class SimMatrixReport
{
    private const string SystemsFile = "src/DK2.Simulation/Systems/SimulationSystems.cs";

    internal static string Markdown(SimMatrixResult result)
    {
        var sb = new StringBuilder();
        var c = CultureInfo.InvariantCulture;
        sb.Append("# Simulation read/write matrix\n\n");
        sb.Append("Generated by `dk2tools simmatrix` ([issue 9](https://github.com/franjom/netherhold/issues/9), WP6); do not edit. Which world state each system reads and writes, ")
          .Append($"in the order [`SimulationSystems.Default()`]({WikiPages.Blob}{SystemsFile}) runs them. ")
          .Append("It is read from the source with Roslyn: every method a system's entry point can reach, through every ")
          .Append("implementation of an interface or virtual call.\n\n");
        sb.Append(c, $"{result.Files} source files, {result.Rows.Count} rows, {result.Methods} methods reached, ")
          .Append(c, $"{result.StateTypes.Count} state types.\n\n");
        sb.Append("**Legend.** `W` written, `R` read and not written. Upper case is the core view, which stops at the hubs ")
          .Append($"({string.Join(" and ", result.Hubs.Select(h => $"`{h.Name}`"))}); lower case is what a row reaches only ")
          .Append("through a hub, so `Rw` is read by the row itself and written only through a hub. A step (↳) runs inside its ")
          .Append("container once per creature or room, in the order shown. Rooms holds the state a room keeps from tick ")
          .Append("to tick; reading `RoomInstance`, the room as its tiles describe it, counts as reading Rooms, while ")
          .Append("rebuilding it is a write of Caches & scratch.\n\n");

        sb.Append("## Matrix\n\n");
        sb.Append("| # | System |");
        foreach (var column in StateModel.Columns) sb.Append(' ').Append(column).Append(" |");
        sb.Append("\n|---:|---|");
        foreach (var _ in StateModel.Columns) sb.Append(":-:|");
        sb.Append('\n');
        string? phase = null;
        foreach (var row in result.Rows)
        {
            if (row.Row.Phase != phase)
            {
                phase = row.Row.Phase;
                sb.Append("| | **").Append(phase).Append("** |");
                foreach (var _ in StateModel.Columns) sb.Append(" |");
                sb.Append('\n');
            }
            sb.Append(c, $"| {row.Row.Number} | ").Append(Label(row.Row)).Append(" |");
            for (int i = 0; i < StateModel.Columns.Length; i++)
                sb.Append(' ').Append(Cell(row.Core.Cells[i], row.Full.Cells[i])).Append(" |");
            sb.Append('\n');
        }

        sb.Append("\n## Writers by column\n\n");
        sb.Append("The rows that write each column, in tick order; those after \"through a hub\" write it only there.\n\n");
        for (int i = 0; i < StateModel.Columns.Length; i++)
        {
            var core = result.Rows.Where(r => r.Core.Cells[i] == "W").Select(r => r.Row).ToArray();
            var hub = result.Rows.Where(r => r.Core.Cells[i] != "W" && r.Full.Cells[i] == "W").Select(r => r.Row).ToArray();
            sb.Append("- **").Append(StateModel.Columns[i]).Append(c, $"** ({core.Length}");
            if (hub.Length > 0) sb.Append(c, $" + {hub.Length}");
            sb.Append("): ").Append(core.Length == 0 ? "none" : string.Join(", ", core.Select(Short)));
            if (hub.Length > 0) sb.Append("; through a hub: ").Append(string.Join(", ", hub.Select(Short)));
            sb.Append('\n');
        }

        sb.Append("\n## Hubs\n\n");
        sb.Append("| Hub | Rows that reach it | Methods it reaches | Rows |\n|---|---:|---:|---|\n");
        foreach (var hub in result.Hubs)
            sb.Append(c, $"| `{hub.Name}` | {hub.Rows.Count} | {hub.Methods} | {string.Join(", ", hub.Rows)} |\n");

        sb.Append("\n## Neighbours that share no state\n\n");
        sb.Append("Consecutive systems, or consecutive steps of one container, where neither writes a field the other reads ")
          .Append("or writes; a container counts with all its steps. As far as data goes, their order is free; the order may ")
          .Append("still be DK2's.\n\n");
        int coreFree = result.FreePairs.Count(p => p.Core), fullFree = result.FreePairs.Count(p => p.Full);
        sb.Append(c, $"{coreFree} pairs in the core view, {fullFree} when the hubs are counted.\n\n");
        if (result.FreePairs.Count > 0)
        {
            sb.Append("| Rows | Core | Through hubs |\n|---|:-:|:-:|\n");
            foreach (var pair in result.FreePairs)
                sb.Append(c, $"| {Short(result.Rows[pair.First - 1].Row)} → {Short(result.Rows[pair.Second - 1].Row)} | {(pair.Core ? "free" : "")} | {(pair.Full ? "free" : "")} |\n");
        }

        sb.Append("\n## Static state\n\n");
        sb.Append("Static fields count as state only when something writes them; each is shared by every world on its ")
          .Append("thread (`[ThreadStatic]`) or in the process, not held per world.\n\n");
        AppendFields(sb, result.StaticState, withColumn: true);

        sb.Append("\n## Fields owned by systems\n\n");
        sb.Append("Written fields of a system class, or of an object only a system holds. They are outside the matrix: ")
          .Append("scratch, caches or per-tick flags that should not carry state from one system to another.\n\n");
        AppendFields(sb, result.SystemOwned, withColumn: false);

        if (result.Unmapped.Count > 0)
        {
            sb.Append("\n## Unmapped members\n\n");
            sb.Append("Members of `WorldState` or `SimulationContext` the column table does not name; counted as World.\n\n");
            foreach (var name in result.Unmapped) sb.Append("- `").Append(name).Append("`\n");
        }

        sb.Append("\n## What it does not see\n\n");
        sb.Append("- A write through a collection, span or `ref` local that a parameter or a call handed in: only the element's ")
          .Append("own fields are seen, not the field that holds the collection.\n")
          .Append("- A mutation through a method that returns a collection; through a get-only property that returns a field ")
          .Append("(`RawGraveyards => _graveyards`) it is seen.\n")
          .Append("- Field initialisers and primary constructors are not walked.\n")
          .Append("- Calls through a delegate are counted (`delegateCalls` in the JSON) and not followed; raising an event ")
          .Append("or calling a delegate field writes Events out when the field is an output, and nothing otherwise.\n")
          .Append("- A constructor flag such as `lays: false` is not evaluated; the row reaches every branch.\n")
          .Append("- Objects a method creates are not written by it, so filling a new object before storing it is not a write.\n");
        sb.Append("\nThe same data with the fields behind each cell is `").Append(SimMatrixCommand.PageName).Append(".json`.\n");
        return sb.ToString();
    }

    internal static string Json(SimMatrixResult result)
    {
        using var stream = new MemoryStream();
        using (var w = new Utf8JsonWriter(stream, new JsonWriterOptions { Indented = true, Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping }))
        {
            w.WriteStartObject();
            w.WriteNumber("files", result.Files);
            w.WriteNumber("methods", result.Methods);
            Strings(w, "columns", StateModel.Columns);
            w.WriteStartArray("rows");
            foreach (var row in result.Rows)
            {
                w.WriteStartObject();
                w.WriteNumber("number", row.Row.Number);
                w.WriteString("phase", row.Row.Phase);
                w.WriteString("name", row.Row.Name);
                w.WriteString("kind", row.Row.Kind switch { RowKind.System => "system", RowKind.CreatureStep => "creature-step", _ => "room-step" });
                if (row.Row.Parent > 0) w.WriteNumber("parent", row.Row.Parent);
                Strings(w, "entries", row.Row.Entries.Select(e => $"{SimRows.Display(e.ContainingType)}.{e.Name}"));
                View(w, "core", row.Core, null);
                View(w, "throughHubs", row.Full, row.Core);
                w.WriteEndObject();
            }
            w.WriteEndArray();
            w.WriteStartArray("hubs");
            foreach (var hub in result.Hubs)
            {
                w.WriteStartObject();
                w.WriteString("name", hub.Name);
                w.WriteNumber("methods", hub.Methods);
                w.WriteStartArray("rows");
                foreach (int n in hub.Rows) w.WriteNumberValue(n);
                w.WriteEndArray();
                w.WriteEndObject();
            }
            w.WriteEndArray();
            w.WriteStartObject("stateTypes");
            foreach (var (type, column) in result.StateTypes.OrderBy(p => p.Key, StringComparer.Ordinal)) w.WriteString(type, column);
            w.WriteEndObject();
            Strings(w, "multiColumnTypes", result.SharedTypes);
            Strings(w, "unmapped", result.Unmapped);
            Fields(w, "staticState", result.StaticState);
            Fields(w, "systemOwned", result.SystemOwned);
            w.WriteEndObject();
        }
        return Encoding.UTF8.GetString(stream.ToArray()).Replace("\r\n", "\n") + "\n";
    }

    /// <summary>A view; with <paramref name="core"/>, the full view's fields that the core view lacks.</summary>
    private static void View(Utf8JsonWriter w, string name, RowView view, RowView? core)
    {
        IEnumerable<string> Added(IReadOnlyList<string> full, Func<RowView, IReadOnlyList<string>> part) =>
            core is null ? full : full.Except(part(core), StringComparer.Ordinal);
        w.WriteStartObject(name);
        w.WriteNumber("methods", view.Methods);
        w.WriteNumber("delegateCalls", view.DelegateCalls);
        Strings(w, "cells", view.Cells);
        Strings(w, "hubs", view.Hubs);
        Strings(w, "writes", Added(view.Writes, v => v.Writes));
        Strings(w, "reads", Added(view.Reads, v => v.Reads.Concat(v.Writes).ToArray()));
        Strings(w, "systemOwnedWrites", Added(view.SystemOwnedWrites, v => v.SystemOwnedWrites));
        w.WriteEndObject();
    }

    private static void Fields(Utf8JsonWriter w, string name, IEnumerable<WrittenField> fields)
    {
        w.WriteStartArray(name);
        foreach (var field in fields)
        {
            w.WriteStartObject();
            w.WriteString("field", field.Name);
            if (field.Column.Length > 0) w.WriteString("column", field.Column);
            w.WriteStartArray("writers");
            foreach (int n in field.Rows) w.WriteNumberValue(n);
            w.WriteEndArray();
            w.WriteEndObject();
        }
        w.WriteEndArray();
    }

    private static void Strings(Utf8JsonWriter w, string name, IEnumerable<string> values)
    {
        w.WriteStartArray(name);
        foreach (var value in values) w.WriteStringValue(value);
        w.WriteEndArray();
    }

    private static void AppendFields(StringBuilder sb, IReadOnlyList<WrittenField> fields, bool withColumn)
    {
        if (fields.Count == 0)
        {
            sb.Append("None.\n");
            return;
        }
        sb.Append(withColumn ? "| Field | Column | Written by rows |\n|---|---|---|\n" : "| Field | Written by rows |\n|---|---|\n");
        foreach (var field in fields)
        {
            sb.Append("| `").Append(field.Name).Append("` |");
            if (withColumn) sb.Append(' ').Append(field.Column).Append(" |");
            sb.Append(' ').Append(string.Join(", ", field.Rows)).Append(" |\n");
        }
    }

    private static string Cell(string core, string full) =>
        core == full ? core : core + full.ToLowerInvariant();

    private static string Label(SimRow row) =>
        (row.Parent > 0 ? "&nbsp;&nbsp;↳ " : "") + "`" + row.Name.Replace("|", "\\|", StringComparison.Ordinal) + "`";

    private static string Short(SimRow row) => $"{row.Number} `{row.Name}`";
}
