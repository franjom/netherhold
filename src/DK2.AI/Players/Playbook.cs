using System.Collections.ObjectModel;
using System.Globalization;
using DK2.Data.Model;

namespace DK2.AI.Players;

/// <summary>What a playbook item is: something a keeper's panel offers, or a creature type.</summary>
public enum PlaybookItemKind : byte { Room, Spell, Door, Trap, Creature }

/// <summary>One item of a level (stage 3 plan, Task 3b), written <c>kind:Name</c>, for instance
/// <c>room:Library</c> or <c>spell:Thunderbolt</c>; the name is the game data's (a room's
/// <see cref="RoomTypeId"/> name).</summary>
public readonly record struct PlaybookItem(PlaybookItemKind Kind, string Name)
{
    public static PlaybookItem Room(RoomTypeId room) => new(PlaybookItemKind.Room, room.ToString());

    public override string ToString() => Kind.ToString().ToLowerInvariant() + ":" + Name;

    /// <summary>Reads <c>kind:Name</c>; the kind exactly as written by <see cref="ToString"/>, the name non-empty.</summary>
    public static bool TryParse(string? text, out PlaybookItem item)
    {
        item = default;
        int colon = text?.IndexOf(':', StringComparison.Ordinal) ?? -1;
        if (colon <= 0 || colon == text!.Length - 1 || text[(colon + 1)..].Trim() != text[(colon + 1)..]) return false;
        string kind = text[..colon];
        foreach (PlaybookItemKind k in (PlaybookItemKind[])Enum.GetValues(typeof(PlaybookItemKind)))
            if (k.ToString().ToLowerInvariant() == kind) { item = new PlaybookItem(k, text[(colon + 1)..]); return true; }
        return false;
    }
}

/// <summary>An item the level's script or research may make available (or take away) during play.</summary>
public sealed record PlaybookChange(PlaybookItem Item, bool ToAvailable, string By);

/// <summary>Where a value comes from: a cited source, or a tuner run on a named commit.</summary>
public enum PlaybookProvenance : byte { Researched, Tuned }

/// <summary>An integer strategy value the playbook sets, with the range a tuner may search.
/// A <see cref="PlaybookProvenance.Tuned"/> value names the commit it was proven on and that
/// commit's hash version; it is stale once the simulation's hash version differs.</summary>
public sealed record PlaybookTunable(string Path, int Value, int Min, int Max, PlaybookProvenance Provenance,
    string? Source = null, string? ProvenOn = null, ulong? HashVersion = null);

/// <summary>Veteran knowledge or a scripted event, each with its source (a doc, a trigger id, a map dump).</summary>
public sealed record PlaybookNote(string Kind, string Text, string Source);

/// <summary>Per-level run limits; each overrides the harness default unless its flag is given.</summary>
public sealed record PlaybookCaps(int? MaxTicks = null, int? MaxActions = null, int? WallSeconds = null, int? OutputMiB = null);

/// <summary>What <see cref="Playbook.Review"/> found: problems refuse the playbook, warnings do not.</summary>
public sealed record PlaybookReview(IReadOnlyList<string> Problems, IReadOnlyList<string> Warnings);

/// <summary>
/// One level's playbook (campaign bot stage 3 plan, Task 3b): what the level offers (generated by
/// <c>DK2.Harness playbook-available</c>, never hand-written), the plan (rooms in order, extra rooms,
/// the knowledge rules applying only where a playbook asks), integer tunables with their ranges and
/// provenance, notes, events and caps. Definition data, loaded before tick 0; read-only during play.
/// </summary>
public sealed record Playbook
{
    /// <summary>A tunable path the playbook may set, its bounds, and how it changes a strategy.</summary>
    private sealed record Knob(int Floor, int Ceiling, Func<PlayerStrategy, int, PlayerStrategy> Set);

    private static readonly IReadOnlyDictionary<string, Knob> Knobs = new Dictionary<string, Knob>(StringComparer.Ordinal)
    {
        ["strategy.room-side"] = new(1, 15, (s, v) => s with { RoomSide = v }),
        ["strategy.max-outstanding-tags"] = new(1, 64, (s, v) => s with { MaxOutstandingTags = v }),
        ["strategy.home-guard-tiles"] = new(0, 64, (s, v) => s with { HomeGuardTiles = v }),
        ["strategy.lair-tiles-per-creature"] = new(1, 9, (s, v) => s with { LairTilesPerCreature = v }),
        ["strategy.creatures-per-hatchery-tile"] = new(1, 9, (s, v) => s with { CreaturesPerHatcheryTile = v }),
        ["strategy.treasury-full-percent"] = new(1, 100, (s, v) => s with { TreasuryFullPercent = v }),
        ["strategy.tiles-per-working-creature"] = new(1, 25, (s, v) => s with { TilesPerWorkingCreature = v }),
        ["strategy.use-room-every-ticks"] = new(1, 4800, (s, v) => s with { UseRoomEveryTicks = v }),
        ["strategy.use-room-min-gold"] = new(0, 1_000_000, (s, v) => s with { UseRoomMinGold = v }),
        ["strategy.enemy-clearance-tiles"] = new(0, 32, (s, v) => s with { EnemyClearanceTiles = v }),
        ["strategy.pit-fighters"] = new(0, 16, (s, v) => s with { PitFighters = v }),
        ["strategy.scouts"] = new(0, 1, (s, v) => s with { Scouts = v }),
    };

    /// <summary>The paths a tunable may name, in order.</summary>
    public static IReadOnlyList<string> TunablePaths { get; } = new ReadOnlyCollection<string>([.. Knobs.Keys.OrderBy(k => k, StringComparer.Ordinal)]);

    public required string Level { get; init; }
    public IReadOnlyList<PlaybookItem> Start { get; init; } = [];
    public IReadOnlyList<PlaybookItem> Creatures { get; init; } = [];
    public IReadOnlyList<PlaybookChange> MayChange { get; init; } = [];
    /// <summary>The rooms to keep, in build order; null keeps the player's default.</summary>
    public IReadOnlyList<RoomTypeId>? Rooms { get; init; }
    /// <summary>The rooms built once the listed ones stand, in order; null keeps the player's default.</summary>
    public IReadOnlyList<RoomTypeId>? ExtraRooms { get; init; }
    /// <summary>Knowledge rules (<c>applies: playbook</c>) that act on this level.</summary>
    public IReadOnlyList<string> Rules { get; init; } = [];
    public IReadOnlyList<PlaybookTunable> Tunables { get; init; } = [];
    public IReadOnlyList<PlaybookNote> Notes { get; init; } = [];
    public IReadOnlyList<PlaybookNote> Events { get; init; } = [];
    public PlaybookCaps Caps { get; init; } = new();

    /// <summary>Every problem and warning at once. A planned room the level neither offers at the start
    /// nor may make available is a problem; one it only may make available, a warning. A tuned value
    /// proven at another hash version than <paramref name="hashVersion"/> is stale: a warning.</summary>
    public PlaybookReview Review(ulong hashVersion)
    {
        var problems = new List<string>();
        var warnings = new List<string>();
        if (string.IsNullOrWhiteSpace(Level) || !Level.StartsWith("campaign:", StringComparison.Ordinal))
            problems.Add($"level '{Level}' is not a campaign level (campaign:<name>)");

        Unique("available start", Start.Select(i => i.ToString()));
        Unique("available creatures", Creatures.Select(i => i.ToString()));
        if (Creatures.Any(c => c.Kind != PlaybookItemKind.Creature)) problems.Add("available creatures lists an item that is not a creature");
        if (Start.Any(c => c.Kind == PlaybookItemKind.Creature)) problems.Add("available start lists a creature; creatures go under available creatures");
        foreach (PlaybookChange change in MayChange)
            if (string.IsNullOrWhiteSpace(change.By)) problems.Add($"may-change {change.Item} says nothing of what changes it");

        IReadOnlyList<RoomTypeId> planned = [.. Rooms ?? [], .. ExtraRooms ?? []];
        Unique("planned rooms", planned.Select(r => r.ToString()));
        foreach (RoomTypeId room in planned)
        {
            PlaybookItem item = PlaybookItem.Room(room);
            if (Start.Contains(item)) continue;
            if (MayChange.Any(c => c.Item == item && c.ToAvailable)) warnings.Add($"{item} is planned but only may become available ({string.Join(", ", MayChange.Where(c => c.Item == item && c.ToAvailable).Select(c => c.By))})");
            else problems.Add($"{item} is planned but the level neither offers it at the start nor may make it available");
        }

        Unique("rules", Rules);
        if (Rules.Any(string.IsNullOrWhiteSpace)) problems.Add("a rule id is empty");

        Unique("tunables", Tunables.Select(t => t.Path));
        foreach (PlaybookTunable t in Tunables)
        {
            if (!Knobs.TryGetValue(t.Path, out Knob? knob))
            {
                problems.Add($"tunable '{t.Path}' is not one of {string.Join(", ", TunablePaths)}");
                continue;
            }
            if (t.Min > t.Max || t.Value < t.Min || t.Value > t.Max)
                problems.Add(Invariant($"tunable {t.Path}: value {t.Value} is not within min {t.Min} and max {t.Max}"));
            if (t.Min < knob.Floor || t.Max > knob.Ceiling)
                problems.Add(Invariant($"tunable {t.Path}: range {t.Min}-{t.Max} leaves {knob.Floor}-{knob.Ceiling}"));
            if (t.Path == "strategy.pit-fighters" && t.Value == 1)
                problems.Add("tunable strategy.pit-fighters: one fighter has no one to pair with; use 0 or 2 or more");
            switch (t.Provenance)
            {
                case PlaybookProvenance.Researched when string.IsNullOrWhiteSpace(t.Source):
                    problems.Add($"tunable {t.Path} is researched but cites no source");
                    break;
                case PlaybookProvenance.Tuned when string.IsNullOrWhiteSpace(t.ProvenOn) || t.HashVersion is null:
                    problems.Add($"tunable {t.Path} is tuned but names no proven-on commit and hash version");
                    break;
                case PlaybookProvenance.Tuned when t.HashVersion != hashVersion:
                    warnings.Add(Invariant($"tunable {t.Path} is stale: proven on {t.ProvenOn} at hash {t.HashVersion}, the simulation is at {hashVersion}"));
                    break;
            }
        }

        foreach (PlaybookNote note in Notes) Sourced("note", note);
        foreach (PlaybookNote e in Events) Sourced("event", e);

        Positive("max-ticks", Caps.MaxTicks);
        Positive("max-actions", Caps.MaxActions);
        Positive("wall-seconds", Caps.WallSeconds);
        if (Caps.OutputMiB is int mib && (mib < 2 || mib > 1024 * 1024)) problems.Add(Invariant($"cap output-mib {mib} is not between 2 and 1048576"));
        return new PlaybookReview(problems, warnings);

        void Unique(string what, IEnumerable<string> names)
        {
            foreach (string name in names.GroupBy(n => n, StringComparer.Ordinal).Where(g => g.Count() > 1).Select(g => g.Key))
                problems.Add($"{what} lists '{name}' more than once");
        }

        void Sourced(string what, PlaybookNote note)
        {
            if (string.IsNullOrWhiteSpace(note.Source)) problems.Add($"{what} '{note.Kind}' cites no source");
        }

        void Positive(string what, int? value)
        {
            if (value is <= 0) problems.Add(Invariant($"cap {what} {value} is not positive"));
        }
    }

    /// <summary>The strategy this playbook makes of <paramref name="strategy"/>: its rooms, extra rooms
    /// and tunable values; everything else unchanged. Call on a playbook whose review found no problems.</summary>
    public PlayerStrategy Apply(PlayerStrategy strategy)
    {
        if (strategy is null) throw new ArgumentNullException(nameof(strategy));
        if (Rooms is not null) strategy = strategy with { Rooms = Rooms };
        if (ExtraRooms is not null) strategy = strategy with { ExtraRooms = ExtraRooms };
        foreach (PlaybookTunable t in Tunables) strategy = Knobs[t.Path].Set(strategy, t.Value);
        return strategy;
    }

    private static string Invariant(FormattableString text) => text.ToString(CultureInfo.InvariantCulture);
}
